// Типографика русского текста: строка не должна заканчиваться предлогом или союзом,
// а тире — начинать новую строку.
// Применяется при выводе текста на страницу; сами данные в site.ts остаются с обычными пробелами.

const NBSP = ' '

// Короткие слова, которые нельзя оставлять в конце строки.
const SHORT = [
  'в', 'во', 'к', 'ко', 'с', 'со', 'у', 'о', 'об', 'и', 'а', 'но', 'на', 'по', 'за', 'до', 'из', 'от',
  'не', 'ни', 'же', 'бы', 'ли', 'или', 'для', 'под', 'при', 'без', 'над',
]
const shortWord = new RegExp(`(^|[\\s${NBSP}(«])(${SHORT.join('|')}) `, 'giu')

/** Привязать предлоги и союзы к следующему слову, а тире — к предыдущему. */
export function typo(text: string): string {
  return (
    text
      // дважды: подряд идущие короткие слова («и в», «не на») делят один пробел
      .replace(shortWord, `$1$2${NBSP}`)
      .replace(shortWord, `$1$2${NBSP}`)
      .replace(/ —/g, `${NBSP}—`)
  )
}
